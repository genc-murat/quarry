import { useEffect, useState } from "react";

import { Button } from "@/components/ui/button";
import { Checkbox } from "@/components/ui/checkbox";
import { Dialog } from "@/components/ui/dialog";
import { Input, Label } from "@/components/ui/input";
import { qualifiedName, quoteIdentifier, type ObjectRef, type SqlDialect } from "@/lib/objects";
import type { ColumnDefinition, ColumnSchema, ObjectDetail } from "@/lib/types";

const COMMON_TYPES = [
  "INT",
  "BIGINT",
  "SMALLINT",
  "SERIAL",
  "VARCHAR(255)",
  "TEXT",
  "BOOLEAN",
  "DATE",
  "TIMESTAMP",
  "TIMESTAMPTZ",
  "DECIMAL(12,2)",
  "JSON",
  "UUID",
];

interface Props {
  open: boolean;
  mode: "add" | "alter";
  onClose: () => void;
  objectRef: ObjectRef;
  detail: ObjectDetail;
  initial?: ColumnSchema;
  dialect: SqlDialect;
  busy?: boolean;
  onRun: (column: ColumnDefinition, renameTo?: string) => void;
}

export function ColumnDialog({
  open,
  mode,
  onClose,
  objectRef,
  detail,
  initial,
  dialect,
  busy,
  onRun,
}: Props) {
  const [name, setName] = useState("");
  const [dataType, setDataType] = useState("VARCHAR(255)");
  const [nullable, setNullable] = useState(true);
  const [defaultValue, setDefaultValue] = useState("");
  const [isPrimaryKey, setIsPrimaryKey] = useState(false);
  const [isAutoIncrement, setIsAutoIncrement] = useState(false);
  const [comment, setComment] = useState("");
  const [after, setAfter] = useState("");
  const [renameTo, setRenameTo] = useState("");

  useEffect(() => {
    if (!open) return;
    setName(initial?.name ?? "");
    setDataType(initial?.dataType ?? "VARCHAR(255)");
    setNullable(initial?.nullable ?? true);
    setDefaultValue(initial?.defaultValue?.toString() ?? "");
    setIsPrimaryKey(initial?.isPrimaryKey ?? false);
    setIsAutoIncrement(initial?.isAutoIncrement ?? false);
    setComment(initial?.comment ?? "");
    setAfter("");
    setRenameTo("");
  }, [open, initial]);

  const quote = detail.identifierQuote || '"';
  const table = qualifiedName(objectRef, quote);

  function definition(): string {
    // SQLite has no identity clause: a lone `INTEGER PRIMARY KEY AUTOINCREMENT`
    // is its only auto-assigning column, so mirror the backend renderer.
    if (dialect === "sqlite" && isAutoIncrement) {
      return `${quoteIdentifier(name.trim() || "column", quote)} INTEGER PRIMARY KEY AUTOINCREMENT`;
    }
    let sql = `${quoteIdentifier(name.trim() || "column", quote)} ${dataType.trim() || "text"}`;
    if (isAutoIncrement) {
      if (dialect === "mysql") sql += " AUTO_INCREMENT";
      else if (dialect === "sqlserver") sql += " IDENTITY(1,1)";
      else sql += " GENERATED BY DEFAULT AS IDENTITY";
    }
    sql += nullable ? " NULL" : " NOT NULL";
    if (defaultValue.trim()) sql += ` DEFAULT ${defaultValue.trim()}`;
    if (isPrimaryKey) sql += " PRIMARY KEY";
    if (dialect === "mysql" && comment.trim()) sql += ` COMMENT '${comment.replace(/'/g, "''")}'`;
    return sql;
  }

  // `AFTER` is MySQL-only; other dialects silently drop the hint (as the backend does).
  const afterClause =
    dialect === "mysql" && after.trim() ? ` AFTER ${quoteIdentifier(after.trim(), quote)}` : "";
  // T-SQL's `ALTER TABLE ADD` takes no `COLUMN` keyword.
  const addForm =
    dialect === "sqlserver"
      ? `ALTER TABLE ${table} ADD ${definition()}${afterClause};`
      : `ALTER TABLE ${table} ADD COLUMN ${definition()}${afterClause};`;
  const preview =
    mode === "add"
      ? addForm
      : dialect === "mysql"
        ? `ALTER TABLE ${table} CHANGE COLUMN ${quoteIdentifier(initial?.name ?? name, quote)} ${definition()}${afterClause};`
        : dialect === "sqlite"
          ? renameTo.trim() && renameTo.trim() !== initial?.name
            ? `ALTER TABLE ${table} RENAME COLUMN ${quoteIdentifier(initial?.name ?? name, quote)} TO ${quoteIdentifier(renameTo.trim(), quote)};`
            : "-- SQLite can only rename a column in place; recreate the table to change its type."
          : dialect === "sqlserver"
            ? [
                renameTo.trim() && renameTo.trim() !== initial?.name
                  ? `EXEC sp_rename '${table}.${quoteIdentifier(initial?.name ?? name, quote)}', '${renameTo.trim().replace(/'/g, "''")}', 'COLUMN';`
                  : null,
                `ALTER TABLE ${table} ALTER COLUMN ${quoteIdentifier(initial?.name ?? name, quote)} ${dataType.trim() || "text"} ${nullable ? "NULL" : "NOT NULL"};`,
                defaultValue.trim()
                  ? `-- SQL Server stores a default as a named constraint; change it in SQL.`
                  : null,
              ]
                .filter(Boolean)
                .join("\n")
            : [
                renameTo.trim() && renameTo.trim() !== initial?.name
                  ? `ALTER TABLE ${table} RENAME COLUMN ${quoteIdentifier(initial?.name ?? name, quote)} TO ${quoteIdentifier(renameTo.trim(), quote)};`
                  : null,
                `ALTER TABLE ${table} ALTER COLUMN ${quoteIdentifier(initial?.name ?? name, quote)} TYPE ${dataType.trim()};`,
              ]
                .filter(Boolean)
                .join("\n");

  const sqliteRenameOnly = dialect === "sqlite" && mode === "alter";
  const canSubmit =
    Boolean(name.trim()) &&
    !busy &&
    (!sqliteRenameOnly || Boolean(renameTo.trim() && renameTo.trim() !== initial?.name));

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title={mode === "add" ? `Add column to ${objectRef.object}` : `Alter ${initial?.name ?? "column"}`}
      description={
        sqliteRenameOnly
          ? "SQLite supports renaming a column here; changing its type or constraints requires rebuilding the table."
          : "Types are used verbatim; use a raw expression for defaults (e.g. CURRENT_TIMESTAMP)."
      }
      footer={
        <>
          <Button variant="ghost" size="sm" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <Button
            size="sm"
            disabled={!canSubmit}
            onClick={() =>
              onRun(
                {
                  name: name.trim(),
                  dataType: dataType.trim() || "text",
                  nullable,
                  defaultValue: defaultValue.trim() || null,
                  isPrimaryKey,
                  isAutoIncrement,
                  comment: comment.trim() || null,
                  after: after.trim() || null,
                },
                renameTo.trim() || undefined,
              )
            }
          >
            {busy ? "Running…" : mode === "add" ? "Add column" : "Save changes"}
          </Button>
        </>
      }
    >
      <div className="space-y-4">
        <div className="grid grid-cols-2 gap-3">
          <div>
            <Label className="mb-2 block">Name</Label>
            <Input value={name} onChange={(event) => setName(event.target.value)} />
          </div>
          <div>
            <Label className="mb-2 block">Type</Label>
            <Input
              value={dataType}
              list="column-type-options"
              onChange={(event) => setDataType(event.target.value)}
            />
            <datalist id="column-type-options">
              {COMMON_TYPES.map((type) => (
                <option key={type} value={type} />
              ))}
            </datalist>
          </div>
        </div>

        <div className="grid grid-cols-2 gap-3">
          <div>
            <Label className="mb-2 block">Default (raw)</Label>
            <Input
              value={defaultValue}
              placeholder="e.g. 0 or CURRENT_TIMESTAMP"
              onChange={(event) => setDefaultValue(event.target.value)}
            />
          </div>
          {mode === "alter" && quote !== "`" ? (
            <div>
              <Label className="mb-2 block">Rename to</Label>
              <Input value={renameTo} onChange={(event) => setRenameTo(event.target.value)} />
            </div>
          ) : (
            <div>
              <Label className="mb-2 block">After column</Label>
              <Input
                value={after}
                list="column-name-options"
                onChange={(event) => setAfter(event.target.value)}
              />
              <datalist id="column-name-options">
                {detail.schema.columns.map((column) => (
                  <option key={column.name} value={column.name} />
                ))}
              </datalist>
            </div>
          )}
        </div>

        <div className="flex flex-wrap items-center gap-4">
          <Checkbox label="Nullable" checked={nullable} onChange={(e) => setNullable(e.target.checked)} />
          <Checkbox
            label="Primary key"
            checked={isPrimaryKey}
            onChange={(e) => setIsPrimaryKey(e.target.checked)}
          />
          <Checkbox
            label="Auto increment"
            checked={isAutoIncrement}
            onChange={(e) => setIsAutoIncrement(e.target.checked)}
          />
        </div>

        <div>
          <Label className="mb-2 block">Comment</Label>
          <Input value={comment} onChange={(event) => setComment(event.target.value)} />
        </div>

        <div>
          <Label className="mb-2 block">SQL preview</Label>
          <pre className="max-h-40 overflow-auto whitespace-pre-wrap rounded-md border border-border bg-surface px-3 py-2 font-mono text-[11px] text-muted-foreground">
            {preview}
          </pre>
        </div>
      </div>
    </Dialog>
  );
}
